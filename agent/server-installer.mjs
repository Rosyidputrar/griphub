// Makes griphub-setup.sh: the server/ folder in one shell script the app carries, so setting up a server needs nothing
// but the app. The script unpacks the files into ~/griphub-server, checks each one against its SHA-256 (a paste that lost
// a character stops there) and runs bootstrap.sh with the options it was given. build.mjs puts it in the agent bundle;
// the app copies it as one command to paste into the server's terminal (RemoteMode.setupPaste), or shares it as a file.
//
//   node agent/server-installer.mjs [stamp] > griphub-setup.sh
import { createHash } from "node:crypto";
import { readFileSync, statSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { gzipSync } from "node:zlib";

const here = dirname(fileURLToPath(import.meta.url));
export const SERVER_DIR = join(here, "..", "server");

/** What a server needs, as bootstrap.sh expects it next to itself; field-report.sh for the field test. */
export const SERVER_FILES = ["bootstrap.sh", "griphub-attach", "griphub-hostd.service", "box/box", "box/Containerfile", "field-report.sh"];

/** The heredoc delimiter around each file; no file may contain it on a line of its own. */
const END = "GRIPHUB_FILE";

function wrap(text, width = 76) {
	const lines = [];
	for (let i = 0; i < text.length; i += width) lines.push(text.slice(i, i + width));
	return lines.join("\n");
}

/** The installer for the files in [dir], marked with [stamp] (the agent bundle's version). */
export function serverInstaller(dir = SERVER_DIR, stamp = "") {
	const parts = SERVER_FILES.map((name) => {
		const data = readFileSync(join(dir, name));
		if (data.toString("utf8").split("\n").includes(END)) throw new Error(`${name} contains a line "${END}"`);
		const mode = statSync(join(dir, name)).mode & 0o111 ? "755" : "644";
		const sha = createHash("sha256").update(data).digest("hex");
		const payload = wrap(gzipSync(data, { level: 9 }).toString("base64"));
		return `put ${name} ${mode} ${sha} <<'${END}'\n${payload}\n${END}\n`;
	});
	return `#!/bin/sh
# GripHub server setup${stamp ? ` (${stamp})` : ""}, carried by the app (Settings > Server agent). It holds the server
# files of this app version, unpacks them into ~/griphub-server and runs bootstrap.sh there with the options given:
#
#   sh griphub-setup.sh --pubkey "ssh-ed25519 AAAA... griphub-app" --address agent.example.com
#
# It needs root, and asks sudo for it when run from another account. Add --dry-run to see what bootstrap.sh would do
# (no root needed). Every file is checked against its SHA-256 before anything runs. Generated by
# agent/server-installer.mjs from server/; do not edit.
set -eu
case " $* " in
*" --dry-run "* | *" --help "* | *" -h "*) ;;
*)
	if [ "$(id -u)" != 0 ]; then
		command -v sudo >/dev/null 2>&1 || { echo "error: run this as root" >&2; exit 1; }
		exec sudo sh "$0" "$@"
	fi
	;;
esac
dir=\${GRIPHUB_SERVER_DIR:-$HOME/griphub-server}
mkdir -p "$dir/box"
damaged() {
	echo "error: $1 arrived damaged (part of the setup command was lost on the way); copy it from the app again" >&2
	exit 1
}
put() {
	base64 -d 2>/dev/null | gzip -dc > "$dir/$1.part" 2>/dev/null || damaged "$1"
	[ "$(sha256sum < "$dir/$1.part" | cut -d ' ' -f 1)" = "$3" ] || damaged "$1"
	chmod "$2" "$dir/$1.part"
	mv "$dir/$1.part" "$dir/$1"
}
${parts.join("")}echo "==> GripHub server files are in $dir"
exec bash "$dir/bootstrap.sh" "$@"
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
	process.stdout.write(serverInstaller(SERVER_DIR, process.argv[2] ?? ""));
}
